/** the Chinese for an English literal of the early screens; the version-dated privacy sentence is a template in app-shell.tsx, so it is matched by its shape */
export function zhEarly(en: string): string {
  const hit = EARLY_ZH[en];
  if (hit !== undefined) return hit;
  const m = /^By signing up you accept the \[\[Privacy Policy\]\] \(version (.+)\)$/.exec(en);
  const tpl = EARLY_ZH["By signing up you accept the [[Privacy Policy]] (version {0})"];
  if (m && tpl) return tpl.replace("{0}", m[1]);
  return en;
}
