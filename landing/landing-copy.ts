/* The tiny label inside each language pill, next to the flag. Short on purpose:
   ten pills share two rows of five on a 320 px phone, so Russian is "РУС" and
   not the full "Русский", Spanish, French and German are the two-letter "ES" / "FR" / "DE" the
   way English is "EN", and Arabic is "عربي" (FLAG_NAMES carries the full
   names for the tooltip and screen readers). */
export const LANG_SHORT = { th: "ไทย", en: "EN", zh: "中文", ja: "日本語", ko: "한국어", ru: "РУС", hi: "हिन्दी", es: "ES", fr: "FR", ar: "عربي", de: "DE" };

/* ── which way the page reads ──
   Arabic is right to left. lang-extra.ts has isRtl() / dirOf() for the app. The landing
   bundle could import it (measured: about 1.3 kB more, its catalog loaders are tree-shaken
   away), but that module also carries a LANG_META row per language with fields this page
   never reads and a module-level side effect (it snapshots Number / Date.prototype
   toLocaleString on globalThis for the app's Arabic digit rule), and every kilobyte before
   first paint is a visitor lost. So this is the same one-entry list: LandingPage1 puts
   dir="rtl" on <html> from it, and scripts/smoke-landing-three-langs.mjs fails if
   lang-extra.ts ever marks a different set of languages right to left. */
export const RTL_LANGS = ["ar"];
export const dirOf = (lang) => (RTL_LANGS.includes(lang) ? "rtl" : "ltr");

/* ── which language the page opens in ──
   The URL. Nothing else. /landing/ is Thai, /landing-en/ is English,
   /landing-zh/ is Chinese, /landing-ja/ Japanese, /landing-ko/ Korean,
   /landing-ru/ Russian, /landing-hi/ Hindi, /landing-es/ Spanish,
   /landing-fr/ French, /landing-ar/ Arabic, /landing-de/ German, every time, for everyone.
   (scripts/landing-locales.mjs writes the matching <html lang> — and dir="rtl"
   for Arabic — into each page; presetLang() in LandingPage1 reads it.)

   Two things it deliberately does NOT consult:

   navigator.language — a large share of phones in Thailand are set to
   English, so Thai visitors arriving from a Thai-language ad were greeted in
   English, which is a worse first impression than no detection at all.

   A previously stored choice — this one was a real bug, not a theory. Tapping
   a flag once saved that language, and from then on it overrode the URL: the
   English and Chinese links both opened in Thai for anyone who had ever used
   the site. Three separate links exist precisely so each campaign lands in
   its own language, and a preference set on a different page is no reason to
   break that.

   The flags still switch the language right now, and that choice is still
   written to the guest profile so the APP opens in it after sign-up — it just
   no longer decides what THIS page opens in. */
export function pickLang(preset) {
  if (LANGS.includes(preset)) return preset;
  return "th";
}

