export const FLAGS = { th: "🇹🇭", en: "🇬🇧", zh: "🇨🇳", ja: "🇯🇵", ko: "🇰🇷", ru: "🇷🇺" };   // same six as the app's settings panel (lang-extra.ts LANG_META)
