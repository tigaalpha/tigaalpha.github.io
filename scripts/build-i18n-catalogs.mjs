// Builds the English-keyed catalogs of the extra app languages (i18n-ja/ko/ru/hi/es/fr.ts) from i18n-src/catalog.json.
//   node scripts/build-i18n-catalogs.mjs                       write the .ts files
//   node scripts/build-i18n-catalogs.mjs --check               exit 1 when a .ts file is stale
//   node scripts/build-i18n-catalogs.mjs --merge=DIR [--langs=hi,es,fr]
//                                                              fold DIR/in/batch-NN.json + DIR/out/batch-NN.json into i18n-src/catalog.json first
//                                                              (--langs: only these languages are read from the output files and set; the others stay as they are)
//   node scripts/build-i18n-catalogs.mjs --coverage            list English strings the code uses that the catalog does not have
// catalog.json: { "<English text>": { "ja": "...", "ko": "...", "ru": "...", "hi": "...", "es": "...", "fr": "..." } }. A new language is a new column and a new line in LANGS below.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CAT = path.join(ROOT, "i18n-src", "catalog.json");
const LANGS = ["ja", "ko", "ru", "hi", "es", "fr"];
const arg = n => (process.argv.find(a => a.startsWith("--" + n + "=")) || "").slice(n.length + 3);
const flag = n => process.argv.includes("--" + n);

let catalog = {};
try { catalog = JSON.parse(fs.readFileSync(CAT, "utf8")); } catch (e) { /* first run */ }

const mergeDir = arg("merge");
const mergeLangs = (arg("langs") ? arg("langs").split(",") : LANGS).filter(l => LANGS.includes(l));
if (mergeDir) {
  let added = 0, replaced = 0, files = 0, partial = 0;
  for (const f of fs.readdirSync(path.join(mergeDir, "in")).filter(f => /^batch-[\w]+\.json$/.test(f)).sort()) {
    const src = JSON.parse(fs.readFileSync(path.join(mergeDir, "in", f), "utf8"));
    // one output file per language (out-hi/, out-es/, out-fr/) or the old combined out/ folder
    const outs = {};
    for (const lg of mergeLangs) {
      const per = path.join(mergeDir, "out-" + lg, f), all = path.join(mergeDir, "out", f);
      const file = fs.existsSync(per) ? per : fs.existsSync(all) ? all : null;
      if (file) outs[lg] = JSON.parse(fs.readFileSync(file, "utf8"));
    }
    if (!Object.keys(outs).length) { console.log("no output yet for " + f); continue; }
    files++;
    for (const row of src) {
      const have = catalog[row.en] || {};
      const entry = { ...have };
      for (const lg of mergeLangs) {
        const o = outs[lg] && outs[lg][row.k];
        const t = o && (typeof o === "string" ? o : o[lg]);
        if (typeof t === "string" && t.trim()) entry[lg] = t;
      }
      if (mergeLangs.some(lg => !entry[lg])) { partial++; continue; }   // a half-translated row is not merged
      if (catalog[row.en]) replaced++; else added++;
      catalog[row.en] = entry;
    }
  }
  fs.mkdirSync(path.dirname(CAT), { recursive: true });
  const sorted = Object.fromEntries(Object.keys(catalog).sort().map(k => [k, catalog[k]]));
  fs.writeFileSync(CAT, JSON.stringify(sorted, null, 1) + "\n");
  catalog = sorted;
  console.log(`merged ${files} batch files (${mergeLangs.join(",")}): ${added} added, ${replaced} updated, ${partial} rows skipped for a missing language, ${Object.keys(catalog).length} in the catalog`);
}

if (flag("prune")) {
  const tmp = path.join(ROOT, "i18n-src", ".prune.json");
  execFileSync("node", [path.join(ROOT, "scripts/extract-i18n.mjs"), "--out=" + tmp], { stdio: "ignore" });
  const used = new Set(JSON.parse(fs.readFileSync(tmp, "utf8")).strings.map(x => x.en));
  fs.rmSync(tmp);
  const drop = Object.keys(catalog).filter(k => !used.has(k));
  for (const k of drop) delete catalog[k];
  fs.writeFileSync(CAT, JSON.stringify(Object.fromEntries(Object.keys(catalog).sort().map(k => [k, catalog[k]])), null, 1) + "\n");
  console.log(`pruned ${drop.length} entries the code does not use any more; ${Object.keys(catalog).length} left`);
  if (arg("list")) fs.writeFileSync(arg("list"), JSON.stringify(drop, null, 1));
}

const header = lang => `/* GENERATED by scripts/build-i18n-catalogs.mjs from i18n-src/catalog.json — do not edit by hand.
   English text -> ${lang}. Looked up by lang-extra.ts (xlate); a string that is not here shows its English. */
`;
let stale = 0;
for (const lg of LANGS) {
  const lines = Object.keys(catalog).sort().filter(k => catalog[k][lg]).map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(catalog[k][lg])},`);
  const text = header(lg) + `const cat: Record<string, string> = {\n${lines.join("\n")}\n};\nexport default cat;\n`;
  const file = path.join(ROOT, `i18n-${lg}.ts`);
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (flag("check")) { if (cur !== text) { stale++; console.log("stale: i18n-" + lg + ".ts"); } }
  else if (cur !== text) { fs.writeFileSync(file, text); console.log(`wrote i18n-${lg}.ts (${lines.length} entries, ${(text.length / 1024).toFixed(0)} kB)`); }
}
if (flag("check")) { if (stale) process.exit(1); console.log("catalogs are current"); }

if (flag("coverage")) {
  const tmp = path.join(ROOT, "i18n-src", ".coverage.json");
  execFileSync("node", [path.join(ROOT, "scripts/extract-i18n.mjs"), "--out=" + tmp], { stdio: "ignore" });
  const used = JSON.parse(fs.readFileSync(tmp, "utf8")).strings;
  fs.rmSync(tmp);
  const SKIP = /^(songs-classical\.ts|songs-data\.ts|admin-nav\.tsx|ra-planets\.ts|landing\/|Admin|Lead|Tigamodel)/;
  const pats = Object.keys(catalog).filter(k => /\{\d+\}/.test(k));
  const missing = used.filter(x => !catalog[x.en] && !x.files.every(f => SKIP.test(f)) && x.en.length <= 1200);
  const byFile = {};
  for (const x of missing) for (const f of x.files) byFile[f] = (byFile[f] || 0) + 1;
  console.log(`${used.length} English strings in the code, ${Object.keys(catalog).length} in the catalog (${pats.length} with holes), ${missing.length} not translated`);
  console.log(Object.entries(byFile).sort((a, b) => b[1] - a[1]).slice(0, 15).map(([f, n]) => `  ${f}: ${n}`).join("\n"));
  if (arg("list")) fs.writeFileSync(arg("list"), JSON.stringify(missing, null, 1));
}
